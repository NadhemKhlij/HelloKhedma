// Writes js/config.js from environment variables, so the deployed site gets its Supabase settings
// without committing them. Set these in your host (Cloudflare Pages / Netlify / Vercel):
//   SUPABASE_URL, SUPABASE_ANON_KEY, DEFAULT_COUNTRY (optional, default "fr"),
//   CONTACT_EMAIL (optional: shown on the legal and privacy pages), SENTRY_DSN (optional: error monitoring)
// Locally you can skip the env vars and keep a hand-made js/config.js (copied from config.example.js).
import { existsSync, writeFileSync } from "node:fs";

const target = new URL("../js/config.js", import.meta.url);
const { SUPABASE_URL, SUPABASE_ANON_KEY, DEFAULT_COUNTRY = "fr", CONTACT_EMAIL = "", SENTRY_DSN = "" } = process.env;

if (SUPABASE_URL && SUPABASE_ANON_KEY) {
  const config = { SUPABASE_URL, SUPABASE_ANON_KEY, DEFAULT_COUNTRY, CONTACT_EMAIL, SENTRY_DSN };
  writeFileSync(target, `// Generated by scripts/write-config.mjs. Do not edit on the host.\nexport const CONFIG = ${JSON.stringify(config, null, 2)};\n`);
  console.log("js/config.js written from environment variables.");
} else if (existsSync(target)) {
  console.log("SUPABASE_URL / SUPABASE_ANON_KEY not set; keeping the existing js/config.js.");
} else {
  console.error("Missing SUPABASE_URL and SUPABASE_ANON_KEY, and no js/config.js exists. See README.");
  process.exit(1);
}
